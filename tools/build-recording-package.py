#!/usr/bin/env python3
"""Generate the recording-ready package from a lecture script and segments.json.

Sources of truth:
  02_scripts/lecture_script.md
  04_motion_src/segments.json

Outputs:
  05_recording/manifest.json
  05_recording/cues/<name>.md
  05_recording/checklist.md (segment table refresh)

The command is idempotent. It validates every source before writing anything, so
a bad script never leaves an empty or partially updated package behind.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from script_timing import (
    SEGMENT_TAG,
    TIMING_TAG,
    parse_timing_blocks,
    validate_timing_block,
)

MOTION_MIN_SECONDS = 45.0
MOTION_MAX_SECONDS = 90.0
DEFAULT_CANVAS = {"width": 1920, "height": 1080, "fps": 60}
CHECKLIST_START = "<!-- RECORDING-SEGMENTS:START -->"
CHECKLIST_END = "<!-- RECORDING-SEGMENTS:END -->"
# Generated artifacts use LF on every platform.
LF = chr(10)
CHECKLIST_PATTERN = re.compile(
    re.escape(CHECKLIST_START) + r".*?" + re.escape(CHECKLIST_END),
    re.S,
)


class PackageError(Exception):
    """Raised when source data cannot produce a complete recording package."""


def is_nonempty(path: Path) -> bool:
    try:
        return path.is_file() and bool(path.read_text(encoding="utf-8", errors="replace").strip())
    except OSError:
        return False


def load_segments(episode: Path) -> tuple[dict, list[dict]]:
    path = episode / "04_motion_src" / "segments.json"
    if not path.is_file():
        raise PackageError(f"missing {path.relative_to(episode)}")
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, json.JSONDecodeError) as exc:
        raise PackageError(f"segments.json invalid: {exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("segments"), list):
        raise PackageError("segments.json must contain a segments list")

    entries: list[dict] = []
    seen: set[str] = set()
    for index, raw in enumerate(data["segments"], start=1):
        label = f"segments.json entry #{index}"
        if not isinstance(raw, dict):
            raise PackageError(f"{label} is not an object")
        name = raw.get("name")
        if not isinstance(name, str) or not name.strip():
            raise PackageError(f"{label} has no name")
        name = name.strip()
        if name in seen:
            raise PackageError(f"duplicate segment name: {name}")
        seen.add(name)

        engine = raw.get("engine")
        if engine not in {"motion", "manim"}:
            raise PackageError(f"{name}: engine must be 'motion' or 'manim'")
        order = raw.get("order")
        if isinstance(order, bool) or not isinstance(order, int):
            raise PackageError(f"{name}: missing or invalid order")

        scene = raw.get("scene") or name
        project = raw.get("project") or scene
        if not isinstance(scene, str) or not scene.strip():
            raise PackageError(f"{name}: invalid scene")
        if not isinstance(project, str) or not project.strip():
            raise PackageError(f"{name}: invalid project")
        scene = scene.strip()
        if scene.endswith(".tsx"):
            scene = scene[:-4]
        project = project.strip()
        if project.endswith(".ts"):
            project = project[:-3]

        duration = raw.get("duration_seconds")
        if engine == "motion":
            if isinstance(duration, bool) or not isinstance(duration, (int, float)):
                raise PackageError(f"{name}: missing or invalid duration_seconds")
            duration = float(duration)
            if not (MOTION_MIN_SECONDS <= duration <= MOTION_MAX_SECONDS):
                raise PackageError(
                    f"{name}: duration_seconds {duration:g}s is outside "
                    f"{MOTION_MIN_SECONDS:.0f}-{MOTION_MAX_SECONDS:.0f}s"
                )
        entries.append({
            "name": name,
            "engine": engine,
            "order": order,
            "scene": scene,
            "project": project,
            "duration_seconds": float(duration) if isinstance(duration, (int, float)) and not isinstance(duration, bool) else None,
        })

    orders = [entry["order"] for entry in entries]
    if sorted(orders) != list(range(1, len(entries) + 1)):
        raise PackageError(
            "segment order must be continuous 1..N; found "
            + ", ".join(str(order) for order in orders)
        )
    return data, entries


def build_cue_text(name: str, entry: dict, block: dict, url: str) -> str:
    lines = [
        "<!-- Generated by tools/build-recording-package.py. Do not edit by hand. -->",
        "",
        f"# {name} — {entry['duration_seconds']:g}s",
        "",
        f"- Segment: `{name}`",
        f"- Order: {entry['order']}",
        f"- Declared: {entry['duration_seconds']:g}s",
        f"- Recording URL: {url}",
        "",
        "## Cue sheet",
        "",
    ]

    sections: list[dict] = []
    current: dict | None = None
    preface: list[str] = []

    for _lineno, line, escaped in block.get("raw", []):
        if escaped:
            continue
        if SEGMENT_TAG.match(line):
            continue
        timing = TIMING_TAG.match(line)
        if timing:
            if current is not None:
                sections.append(current)
            current = {
                "tag": timing.group(1).upper(),
                "seconds": int(timing.group(2)) * 60 + int(timing.group(3)),
                "instruction": timing.group(4).strip(),
                "narration": [],
            }
            continue
        text = line.strip()
        if not text:
            continue
        if current is None:
            preface.append(text)
        else:
            current["narration"].append(text)

    if current is not None:
        sections.append(current)

    if preface:
        lines.extend(["### Pre-cue narration", ""])
        lines.extend(f"> {text}" for text in preface)
        lines.append("")

    for section in sections:
        stamp = f"{section['seconds'] // 60:02d}:{section['seconds'] % 60:02d}"
        lines.extend([
            f"### {stamp} — {section['tag']}",
            "",
            section["instruction"] or "（待补画面说明）",
            "",
        ])
        if section["narration"]:
            lines.append("> 口播：")
            lines.extend(f"> {text}" for text in section["narration"])
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_checklist_block(segments: list[dict]) -> str:
    lines = [
        CHECKLIST_START,
        "| Order | Segment | URL | Declared | Cue |",
        "| --- | --- | --- | --- | --- |",
    ]
    for segment in segments:
        lines.append(
            f"| {segment['order']} | {segment['name']} | {segment['url']} | "
            f"{segment['declared_seconds']:g}s | {segment['cue']} |"
        )
    lines.append(CHECKLIST_END)
    return "\n".join(lines)


def update_checklist(text: str, block: str, slug: str) -> str:
    if CHECKLIST_PATTERN.search(text):
        return CHECKLIST_PATTERN.sub(block, text, count=1)
    if text.strip():
        return text.rstrip() + "\n\n## 段落清单（由 build-recording-package.py 生成）\n\n" + block + "\n"
    return (
        f"# Recording Checklist — {slug}\n\n"
        "## 段落清单（由 build-recording-package.py 生成）\n\n"
        + block
        + "\n"
    )


def collect_old_statuses(manifest_path: Path) -> dict[str, str]:
    statuses: dict[str, str] = {}
    if not manifest_path.is_file():
        return statuses
    try:
        old = json.loads(manifest_path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, json.JSONDecodeError):
        return statuses
    if isinstance(old, dict) and isinstance(old.get("segments"), list):
        for raw in old["segments"]:
            if isinstance(raw, dict) and isinstance(raw.get("name"), str):
                status = raw.get("record_status")
                statuses[raw["name"]] = status if isinstance(status, str) and status else "NOT_RUN"
    return statuses


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("episode", help="Episode slug under courses/")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--port", type=int, default=9100, help="Port used in record.html URLs")
    parser.add_argument("--check", action="store_true", help="Validate and print the plan without writing")
    args = parser.parse_args()

    root = Path(args.root)
    episode = root / "courses" / args.episode
    if not episode.is_dir():
        print(f"ERROR: episode not found: {episode}", file=sys.stderr)
        return 2

    script_path = episode / "02_scripts" / "lecture_script.md"
    if not script_path.is_file():
        print(f"ERROR: missing {script_path.relative_to(episode)}", file=sys.stderr)
        return 1
    script_text = script_path.read_text(encoding="utf-8", errors="replace")

    errors: list[str] = []
    warnings: list[str] = []

    try:
        data, entries = load_segments(episode)
    except PackageError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    motion_entries = [entry for entry in entries if entry["engine"] == "motion"]
    if not motion_entries:
        print("ERROR: segments.json has no engine=motion entries", file=sys.stderr)
        return 1

    blocks = parse_timing_blocks(script_text)
    blocks_by_name: dict[str, dict] = {}
    for block in blocks:
        name = block["name"]
        if name in blocks_by_name:
            errors.append(f"duplicate [ANIMATION] timing block: {name}")
        blocks_by_name[name] = block

    motion_by_name = {entry["name"]: entry for entry in motion_entries}
    for entry in motion_entries:
        name = entry["name"]
        block = blocks_by_name.get(name)
        if block is None:
            errors.append(f"{name}: missing [ANIMATION] timing block")
            continue
        block_issues, block_warnings = validate_timing_block(
            name,
            block,
            expected_seconds=entry["duration_seconds"],
            expected_order=entry["order"],
        )
        errors.extend(block_issues)
        warnings.extend(block_warnings)

        scene_path = episode / "04_motion_src" / "src" / "scenes" / f"{entry['scene']}.tsx"
        project_path = episode / "04_motion_src" / "src" / "projects" / f"{entry['project']}.ts"
        if not is_nonempty(scene_path):
            errors.append(f"{name}: missing motion scene ({scene_path.relative_to(episode)})")
        if not is_nonempty(project_path):
            errors.append(f"{name}: missing motion project ({project_path.relative_to(episode)})")

    for block in blocks:
        name = block["name"]
        if name in motion_by_name:
            continue
        entry = next((item for item in entries if item["name"] == name), None)
        if entry is not None and entry["engine"] == "manim":
            continue
        if block.get("segments"):
            errors.append(f"{name}: [SEGMENT] has no engine=motion entry in segments.json")

    if errors:
        print(f"Episode: {args.episode}")
        print("Status: FAIL")
        print("Errors:")
        for error in errors:
            print(f"  - {error}")
        for warning in warnings:
            print(f"  - WARN: {warning}")
        return 1

    recording_dir = episode / "05_recording"
    cues_dir = recording_dir / "cues"
    recordings_dir = recording_dir / "recordings"
    manifest_path = recording_dir / "manifest.json"
    checklist_path = recording_dir / "checklist.md"

    old_status = collect_old_statuses(manifest_path)
    manifest_segments = []
    cue_texts: dict[str, str] = {}
    for entry in sorted(motion_entries, key=lambda item: item["order"]):
        name = entry["name"]
        url = f"http://localhost:{args.port}/record.html?segment={name}"
        block = blocks_by_name[name]
        manifest_segments.append({
            "order": entry["order"],
            "name": name,
            "engine": "motion",
            "url": url,
            "declared_seconds": entry["duration_seconds"],
            "cue": f"cues/{name}.md",
            "scene": entry["scene"],
            "project": entry["project"],
            "record_status": old_status.get(name, "NOT_RUN"),
        })
        cue_texts[name] = build_cue_text(name, entry, block, url)

    canvas = data.get("canvas") if isinstance(data.get("canvas"), dict) else DEFAULT_CANVAS
    manifest = {
        "episode": args.episode,
        "engine": "motion",
        "canvas": canvas,
        "segments": manifest_segments,
        "generated_by": "tools/build-recording-package.py",
        "notes": "Generated from 02_scripts/lecture_script.md and 04_motion_src/segments.json. Do not edit by hand.",
    }
    checklist_block = render_checklist_block(manifest_segments)
    old_checklist = checklist_path.read_text(encoding="utf-8", errors="replace") if checklist_path.is_file() else ""
    checklist_text = update_checklist(old_checklist, checklist_block, args.episode)

    print(f"Episode: {args.episode}")
    print(f"Motion segments: {len(manifest_segments)}")
    print(f"Manifest: {manifest_path.relative_to(episode)}")
    print("Cues: " + ", ".join(f"cues/{name}.md" for name in cue_texts))
    print(f"Checklist: {checklist_path.relative_to(episode)}")
    for warning in warnings:
        print(f"  - WARN: {warning}")

    if args.check:
        print("Status: CHECK_ONLY (no files written)")
        return 0

    recording_dir.mkdir(parents=True, exist_ok=True)
    cues_dir.mkdir(parents=True, exist_ok=True)
    recordings_dir.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + LF, encoding="utf-8", newline=LF)
    for name, text in cue_texts.items():
        (cues_dir / f"{name}.md").write_text(text, encoding="utf-8", newline=LF)
    checklist_path.write_text(checklist_text, encoding="utf-8", newline=LF)

    print("Status: WRITTEN")
    return 0


if __name__ == "__main__":
    sys.exit(main())
